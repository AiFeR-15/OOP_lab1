#ifndef POLYNOMIAL_H
#define POLYNOMIAL_H

class Polynomial {
private:
    int n;          // Розмірність (кількість коефіцієнтів)
    double* coef;   // Вказівник на динамічний масив

public:
    // ==========================================
    // БЛОК 1: КОНСТРУКТОРИ
    // ==========================================
    Polynomial();                                // 1. Конструктор за замовчуванням
    Polynomial(int size);                        // 2. Конструктор з параметрами
    Polynomial(const Polynomial& other);         // 3. Конструктор копіювання

    // ==========================================
    // БЛОК 2: ДЕСТРУКТОР
    // ==========================================
    ~Polynomial();

    // ==========================================
    // БЛОК 3: ОПЕРАТОР ПРИСВОЄННЯ
    // ==========================================
    Polynomial& operator=(const Polynomial& other);

    // ==========================================
    // БЛОК 4: ФУНКЦІЇ ВВЕДЕННЯ ТА ВИВЕДЕННЯ
    // ==========================================
    void input();
    void output() const;
};

#endif