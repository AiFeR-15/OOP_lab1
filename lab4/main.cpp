#include <iostream>
#include "Polynomial.h"

using namespace std;

int main() {
    cout << "--- Створення першого многочлена ---" << endl;
    
    // Блок безпечного введення замість жорсткого Polynomial p1(3);
    int size;
    while (true) {
        cout << "Введіть кількість коефіцієнтів (більше 0): ";
        if (cin >> size && size > 0) break;
        cout << "Помилка! Введіть додатнє ціле число.\n";
        cin.clear();
        cin.ignore(10000, '\n');
    }
    Polynomial p1(size); // Працює конструктор з параметрами
    
    p1.input();
    
    cout << "\nВаш перший многочлен (P1): ";
    p1.output();
    cout << "------------------------------------\n";

    cout << "\n--- Створення копії многочлена ---" << endl;
    Polynomial p2 = p1; // Працює конструктор копіювання
    
    cout << "Скопійований многочлен (P2): ";
    p2.output();
    cout << "------------------------------------\n";

    cout << "\n--- Робота з порожнім многочленом ---" << endl;
    Polynomial p3; // Працює конструктор за замовчуванням
    
    cout << "Присвоюємо значення першого многочлена третьому..." << endl;
    p3 = p1; // Працює оператор присвоєння
    
    cout << "Третій многочлен після присвоєння (P3): ";
    p3.output();
    cout << "------------------------------------\n";

    cout << "\nПрограма завершує роботу. Відбувається очищення пам'яті:" << endl;
    return 0;
}